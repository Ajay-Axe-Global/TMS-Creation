"""
Emvia: create the order in TMS.

By the time create_order() is called the worker (helpers/tms_worker.py) has already signed the
user in, saved the session and opened the EMPTY NEW-ORDER CARD in `frame`. This module runs the
hand-tested flow script (tms_flow.js, generated by derive_flow.py from the original script) inside
that page: General -> attach file -> Lines -> Order Cargo -> Calculate Revenues -> (Copy Order x
N-1 -> File No. -> list/filter) -> Container No. + Seal No. on every order.

    One container   copies = 0: no Copy Order, no list/filter. The card IS the order; its TMS number is
                    read from the card header. A File No. may never appear — that is fine.
    N containers    fill the first order, Copy Order x (N-1), then set each order's container + seal.

Contract
    create_order(page, frame, payload, log) -> {"orders": {container_no: tms_order_no}, "file_no": str|None,
                                                "log": [script log rows]}
    check_payload(payload) -> [reasons]  asked at Create time, BEFORE anything is queued
    Raises FlowFailed(message, result) when the run did not finish; result keeps any orders it created.

THE MAPPING (source field -> TMS field) lives in to_script_data() below. Items marked ASSUMED were
not confirmed — check them before enabling creation (TMS_CREATE_ENABLED).
"""
import base64
import datetime
import logging
import mimetypes
import os
from pathlib import Path

from helpers.flow_errors import FlowFailed, FlowNotReady   # noqa: F401  (FlowNotReady re-exported)

logger = logging.getLogger("tms_create")

FLOW_JS = Path(__file__).with_name("tms_flow.js")
ATTACHMENT_DOC_TYPE = "ANDER"          # the TMS Document Types zone the arrival notice is dropped on
TRACTION_ORDER = "Import"              # ASSUMED: every shipment is an import (the script's own value)
FLOW_TIMEOUT_SECONDS = int(os.getenv("TMS_FLOW_TIMEOUT_SECONDS", "900"))


# ── mapping ──────────────────────────────────────────────────────────────────

def _d(iso: str | None) -> str:
    """ISO date -> the d/MM/yyyy the TMS fields are typed in ("" when absent)."""
    if not iso:
        return ""
    d = datetime.date.fromisoformat(iso)
    return f"{d.day}/{d.month:02d}/{d.year}"


def check_payload(payload: dict) -> list[str]:
    """Reasons this shipment cannot be created by the flow. Asked when the user clicks Create, so a
    shipment the flow cannot handle is refused up front instead of half-created in TMS."""
    problems = []
    containers = payload["containers"]
    if any(not c["container_no"] for c in containers):
        problems.append("a container has no container number")
    # The flow fills ONE order and copies it, then changes only container no. + seal on each copy, so
    # type and cargo are shared by every container of the shipment.
    differing = [label for label, key in (("container type", "container_type"), ("goods", "goods"),
                                          ("quantity", "qty"), ("gross weight", "gross_weight"))
                 if len({c[key] for c in containers}) > 1]
    if differing:
        problems.append("its containers differ in " + ", ".join(differing) +
                        " — the TMS flow copies the first order, so every container must share these")
    return problems


def to_script_data(payload: dict, file_path: str | None = None) -> dict:
    s, client = payload["shipment"], payload["client"]
    first = payload["containers"][0]
    single = len(payload["containers"]) == 1

    lines = []
    for key, action in (("depot_out", "DEPOT OUT"), ("depot_in", "DEPOT IN")):
        depot = s.get(key)
        if depot:
            lines.append({"action": action, "addressNo": depot["address_no"], "ref1": depot["reference"] or "",
                          "bookedFrom": _d(depot["date"]),
                          "closing": ""})           # ASSUMED: no source for the per-line closing date -> left blank

    cargo = ([{"goodNo": first["goods"], "quantity": first["qty"] or "", "grossWeight": first["gross_weight"] or ""}]
             if first.get("goods") else [])

    return {
        "customer": client["tms_customer_no"],
        "tradelane": client["tms_tradelane_no"],
        "containerSubtype": "",
        "customerRef": s["client_ref"] or "",
        "bookingRef": s["bl_number"] or "",          # ASSUMED: BL number -> Booking Ref.
        # ONE container: typed here, in the General step, so there is nothing to find and edit afterwards.
        # SEVERAL: left empty — every copy would inherit it; each order gets its own after the copies are made.
        "containerNo": first["container_no"] if single else "",
        "vesselName": s["vessel_name"] or "",
        "countryOrigin": s["country_of_origin"] or "",
        "countryDest": s["country_of_destination"] or "",
        "containerType": first["container_type"] or "",
        "closingDatetime": _d(s["closing_date"]),    # ASSUMED: closing_date -> General "Closing Datetime"
        "sealNo": (first["seal_no"] or "") if single else "",
        "tractionOrder": TRACTION_ORDER,
        "carrier": s["carrier"] or "",
        "depotOutFrom": _d(s["depot_out_from"]),
        "vgmClosingDate": _d(s["vgm_closing_date"]),
        "file": {"path": file_path, "docType": ATTACHMENT_DOC_TYPE} if file_path else None,
        "lines": lines,
        "cargo": cargo,
    }


def to_job(payload: dict, file_path: str | None = None) -> dict:
    return {
        "data": to_script_data(payload, file_path),
        "containers": [{"containerNo": c["container_no"], "sealNo": c["seal_no"] or ""} for c in payload["containers"]],
        "calcRevenues": True,
        "timeoutMs": FLOW_TIMEOUT_SECONDS * 1000,
    }


# ── running the script in the TMS page ───────────────────────────────────────

# The original script drops its file through JSRunner.dropFile, which the JS File Runner extension
# provides. This is a stand-in doing the same thing: build the File from the bytes handed in with the
# job and fire dragenter/dragover/drop on the target. The bytes are embedded in the call — nothing
# is exposed to the page that could read other files from this PC.
_SHIM_JS = """(file) => {
  if (!file) { delete window.JSRunner; return false; }
  const bytes = Uint8Array.from(atob(file.b64), c => c.charCodeAt(0));
  window.JSRunner = {
    dropFile: async (target) => {
      const win = target.ownerDocument.defaultView;
      const f = new win.File([bytes], file.name, { type: file.mime });
      const dt = new win.DataTransfer();
      dt.items.add(f);
      for (const type of ["dragenter", "dragover", "drop"])
        target.dispatchEvent(new win.DragEvent(type, { bubbles: true, cancelable: true, dataTransfer: dt }));
      return { name: f.name, size: f.size };
    },
  };
  return true;
}"""

# Script console lines worth showing the user ("===== 1) GENERAL =====", "📌 TMS No.: ...").
_SHOWN_PREFIXES = ("=====", "📌", "📁", "→ opening", "✅", "❌")
# Console lines the platform acts on, not just shows: the script prints them the moment TMS shows the value.
_FIRST_ORDER = "🔖 FIRST ORDER "          # -> log("tms_no", "<order no.>")  saved to the database at once
_FILE_NO = "📁 File No.: "                 # -> log("file_no", "<file no.>")   saved before the list filter


def _file_info(path: str | None):
    if not path:
        return None
    p = Path(path)
    mime = mimetypes.guess_type(p.name)[0] or "application/octet-stream"
    return {"name": p.name, "mime": mime, "b64": base64.b64encode(p.read_bytes()).decode("ascii")}


def run_script(page, source: str, job: dict, log, file_info: dict | None = None) -> dict:
    """Run a flow script (an async function taking the job) in the TMS page and return its result.
    `log(kind, message)` receives the script's step headings while it runs."""
    def on_console(msg):
        text = (msg.text or "").strip()
        for prefix, kind in ((_FIRST_ORDER, "tms_no"), (_FILE_NO, "file_no")):
            if text.startswith(prefix):
                try:
                    log(kind, text[len(prefix):].strip())
                except Exception:
                    logger.exception("checkpoint callback failed")
        if text.startswith(_FIRST_ORDER):
            return
        if text.startswith(_SHOWN_PREFIXES):
            try:
                log("flow", text.strip("= ").replace("=====", "").strip() or text)
            except Exception:
                logger.exception("log callback failed")

    page.evaluate(_SHIM_JS, file_info)
    page.on("console", on_console)
    try:
        return page.evaluate(source, job)
    except Exception as e:                                   # script error, or the page reloaded / closed mid-run
        raise FlowFailed(f"The flow script stopped unexpectedly (the TMS page may have reloaded): {e}")
    finally:
        try:
            page.remove_listener("console", on_console)
        except Exception:
            pass


# Script log statuses that are fine; anything else is something that did not go in as intended.
_BENIGN_STATUS = ("OK", "Clicked", "Dialog closed", "SKIPPED (no file)")


def warnings_from(rows) -> list[str]:
    """What the script could not do or could not confirm, as short "where: what" lines — e.g.
    "Cargo · Good No.: Order Cargo grid not found". The order exists in TMS even then, so the job still
    succeeds, but the page flags the row so nobody assumes it is complete."""
    out = []
    for r in rows or []:
        status = str(r.get("Status") or "")
        if not status or status.startswith(_BENIGN_STATUS):
            continue
        where = " · ".join(str(x) for x in (r.get("Section"), r.get("Line"), r.get("Field")) if x)
        out.append(f"{where}: {status}" if where else status)
    return out


def create_order(page, frame, payload, log):
    engine = os.getenv("TMS_FLOW_ENGINE", "js").strip().lower()      # js (proven live) | native (helpers/tms_creation.py)
    if engine not in ("js", "native"):
        raise FlowNotReady(f"TMS_FLOW_ENGINE must be 'js' or 'native', not '{engine}'")
    if engine == "js" and not FLOW_JS.is_file():
        raise FlowNotReady("clients/emvia/tms_flow.js is missing — run: python -m clients.emvia.derive_flow")
    problems = check_payload(payload)
    if problems:
        raise FlowFailed("Not sent to TMS: " + "; ".join(problems))

    attached = payload.get("file")
    job = to_job(payload, attached["path"] if attached else None)

    if engine == "native":
        from helpers import tms_creation
        result = tms_creation.run(page, frame, job, log)
    else:
        file_info = _file_info(attached["path"]) if attached else None
        result = run_script(page, FLOW_JS.read_text(encoding="utf-8"), job, log, file_info)
    if not result.get("ok"):
        message = result.get("stopped") or "Some containers did not get a TMS order number."
        raise FlowFailed(message, {"orders": result.get("orders") or {}, "file_no": result.get("fileNo"),
                                   "log": result.get("log") or []})
    rows = result.get("log") or []
    return {"orders": result["orders"], "file_no": result.get("fileNo") or None, "log": rows,
            "warnings": warnings_from(rows)}
